// Generates the numbered Lightning SQL onboarding scripts from the same definitions the fixtures use.
// Patterns are adapted from the vendor repo (B:/open-agent-hackathon/vendor/zetaris-getting-started/open_data):
//   EDGAR REST table + flattening schemastore view : rest_apis/sql/rate_limited/01_edgar_company_facts_create.sql:53-90
//   EDGAR submissions + SIC join                    : rest_apis/sql/rate_limited/11_edgar_company_profiles_create.sql:76-101
//   company_dns V4 raw/cache/views                  : rest_apis/sql/rate_limited/12_company_dns_create.sql:126-213
//   USL namespace/COMPILE/ACTIVATE/DQ               : usl/sql/02_sic_edgar_usl_create.sql:87-187
//   non-array JSON REST tables (World Bank)         : rest_apis/sql/non_rate_limited/07_eurostat_create.sql:60-78
// EVERYTHING HERE IS UNVERIFIED AGAINST A LIVE ZETARIS INSTANCE.
import { TABLES } from '../../server/src/zetaris/schema.js';
import {
  COMPANIES, CONCEPTS, TAG_SHORT, WB_COUNTRY, WB_DATE_RANGE, WB_INDICATORS, SIC_V4_ENDPOINT,
  secConceptUrl, secSubmissionsUrl, wbShort, wbUrl,
} from './sources.js';

export interface SqlFile { name: string; content: string }
export interface RawTable { db: string; table: string; endpoint: string }
export interface Generated { files: SqlFile[]; rawTables: RawTable[] }
export interface TagsUsed { [ticker: string]: { [concept: string]: string[] } }

const UA = 'YOUR_APP_NAME YOUR_CONTACT_EMAIL';
const BANNER = (title: string, extra = '') => `-- =============================================================================
-- ${title}
-- Generated by data/generate-sql.ts. Do not edit by hand; edit data/lib/sqlgen.ts and regenerate.
-- STATUS: UNVERIFIED against a live Zetaris instance (written while the instance was not running).
-- Run with: npx tsx data/run-onboarding.ts [--apply]   (dry-run by default; one statement per call)${extra ? '\n' + extra : ''}
-- =============================================================================
`;

const restTable = (db: string, name: string, endpoint: string, header: string) => `CREATE LIGHTNING REST TABLE ${name} FROM ${db} REQUEST(
    endpoint "${endpoint}",
    method "get",
    response_type "json",
    http_encoding "URLENCODED"
) HEADER (
    ${header}
) BODY ();`;

const conceptOf = (tag: string) => CONCEPTS.find((c) => c.tags.includes(tag))!;

export function generate(tagsUsed: TagsUsed): Generated {
  const raw: RawTable[] = [];
  const files: SqlFile[] = [];

  // ---- 00: databases and containers
  files.push({
    name: '00_databases_containers.sql',
    content: BANNER('Step 00: Lightning databases and schemastore containers', '-- CREATE SCHEMASTORE CONTAINER has no IF NOT EXISTS (companion guide section 5): use --skip-exists on re-runs.') + `
CREATE LIGHTNING DATABASE SEC_DATA DESCRIBE BY "SEC EDGAR XBRL facts and submissions REST source";
CREATE LIGHTNING DATABASE COMPANY_DNS DESCRIBE BY "company_dns SIC reference data - section, division, group, class";
CREATE LIGHTNING DATABASE WORLDBANK_REST DESCRIBE BY "World Bank US macro indicators REST source";
CREATE SCHEMASTORE CONTAINER edgar;
CREATE SCHEMASTORE CONTAINER edgar_stage;
CREATE SCHEMASTORE CONTAINER company_dns;
CREATE SCHEMASTORE CONTAINER worldbank;
`,
  });

  // ---- 10: company_dns SIC (V4 only; V3 is deprecated, recipe 12 header)
  raw.push({ db: 'COMPANY_DNS', table: 'sic_codes_v4_raw', endpoint: SIC_V4_ENDPOINT });
  files.push({
    name: '10_company_dns_sic.sql',
    content: BANNER('Step 10: SIC hierarchy from company_dns V4', '-- Rate limited: identify yourself (ZETARIS_USER_AGENT=app_name user@domain.tld). A REST table refetches on EVERY query, so it is cached.') + `
${restTable('COMPANY_DNS', 'sic_codes_v4_raw', SIC_V4_ENDPOINT, `user-agent "${UA}"`)}

CACHE TABLE company_dns.sic_codes_v4_raw;

CREATE SCHEMASTORE VIEW sic_codes_v4_table WITH CONTAINER company_dns AS
SELECT
    item.section_id AS section_id,
    item.section_desc AS section_desc,
    item.division_id AS division_id,
    item.division_desc AS division_desc,
    item.group_id AS group_id,
    item.group_desc AS group_desc,
    item.class_id AS class_id,
    item.class_desc AS class_desc
FROM company_dns.sic_codes_v4_raw
LATERAL VIEW explode(data) AS item;

CREATE SCHEMASTORE VIEW sic_codes_v4_compat_table WITH CONTAINER company_dns AS
SELECT
    item.class_id AS sic_code,
    item.class_desc AS description,
    item.section_id AS division,
    item.section_desc AS division_desc,
    item.division_id AS major_group,
    item.division_desc AS major_group_desc,
    item.group_id AS industry_group,
    item.group_desc AS industry_group_desc
FROM company_dns.sic_codes_v4_raw
LATERAL VIEW explode(data) AS item;
`,
  });

  // ---- 20/21: EDGAR raw REST tables (one per company + tag actually used) and their cache statements
  const rawStmts: string[] = [];
  const cacheStmts: string[] = [];
  const stagePairs: { slug: string; ticker: string; cik: string; tag: string; concept: string; prio: number; rawName: string; stageName: string }[] = [];
  for (const co of COMPANIES) {
    for (const concept of CONCEPTS) {
      for (const tag of tagsUsed[co.ticker]?.[concept.key] ?? []) {
        const rawName = `${co.slug}_${TAG_SHORT[tag]}_facts`;
        raw.push({ db: 'SEC_DATA', table: rawName, endpoint: secConceptUrl(co.cik, tag) });
        rawStmts.push(`-- ${co.name} (CIK ${co.cik}), us-gaap:${tag} -> concept ${concept.key}\n${restTable('SEC_DATA', rawName, secConceptUrl(co.cik, tag), `user-agent "${UA}"`)}`);
        cacheStmts.push(`CACHE TABLE sec_data.${rawName};`);
        stagePairs.push({ slug: co.slug, ticker: co.ticker, cik: co.cik, tag, concept: concept.key, prio: concept.tags.indexOf(tag), rawName, stageName: `${co.slug}_${TAG_SHORT[tag]}_stage` });
      }
    }
  }
  for (const co of COMPANIES) {
    const name = `${co.slug}_submissions_raw`;
    raw.push({ db: 'SEC_DATA', table: name, endpoint: secSubmissionsUrl(co.cik) });
    rawStmts.push(`-- ${co.name} (CIK ${co.cik}) submissions profile\n${restTable('SEC_DATA', name, secSubmissionsUrl(co.cik), `user-agent "${UA}"`)}`);
    cacheStmts.push(`CACHE TABLE sec_data.${name};`);
  }
  files.push({
    name: '20_edgar_raw_tables.sql',
    content: BANNER('Step 20: SEC EDGAR REST tables (companyconcept per company+tag, submissions per company)', `-- SEC limit: 10 req/s and a declared User-Agent. ${rawStmts.length} tables; the runner paces statements (--delay-ms).\n-- Tags come from server/fixtures/zetaris/sources.json (tags that actually supplied annual values).`) + '\n' + rawStmts.join('\n\n') + '\n',
  });
  files.push({
    name: '21_edgar_cache.sql',
    content: BANNER('Step 21: cache every EDGAR raw table', '-- A Lightning REST table re-fetches on every query (companion guide section 5). Without this, one query over\n-- edgar.company_financials would issue one SEC request per raw table. After HTTP 429 wait 60 s and retry that statement.') + '\n' + cacheStmts.join('\n') + '\n',
  });

  // ---- 30: flattening stage views, one per raw tag table
  const stageViews = stagePairs.map((p) => {
    const instant = conceptOf(p.tag).instant;
    const start = instant ? 'CAST(NULL AS STRING) AS period_start' : 'fact.`start` AS period_start';
    const dur = instant
      ? 'fact.`start` IS NULL'
      : 'fact.`start` IS NOT NULL AND datediff(to_date(fact.`end`), to_date(fact.`start`)) BETWEEN 350 AND 380';
    return `-- ${p.ticker} ${p.concept} from us-gaap:${p.tag}${instant ? ' (instant fact: the JSON has no start field, so none is selected)' : ''}
CREATE SCHEMASTORE VIEW ${p.stageName} WITH CONTAINER edgar_stage AS
SELECT
    '${p.ticker}' AS ticker,
    CAST(cik AS BIGINT) AS cik,
    \`entityName\` AS entity_name,
    '${p.concept}' AS concept,
    tag AS xbrl_tag,
    ${p.prio} AS tag_priority,
    year(date_sub(to_date(fact.\`end\`), 45)) AS fiscal_year,
    ${start},
    fact.\`end\` AS period_end,
    CAST(fact.val AS DOUBLE) AS value_usd,
    fact.form AS form_type,
    fact.filed AS filed_date,
    fact.accn AS accession_number
FROM sec_data.${p.rawName}
LATERAL VIEW explode(units.USD) AS fact
WHERE fact.form = '10-K' AND fact.fp = 'FY' AND ${dur};`;
  });
  files.push({
    name: '30_edgar_stage_views.sql',
    content: BANNER('Step 30: flatten each raw EDGAR table (annual 10-K facts only)', '-- Rules (mirrored in data/lib/normalize.ts for the fixtures): form 10-K, fp FY, duration 350-380 days (flow\n-- concepts) or no start date (instant concepts); fiscal_year = YEAR(period_end - 45 days).') + '\n' + stageViews.join('\n\n') + '\n',
  });

  // ---- 40: final EDGAR views the agent queries
  const fin = TABLES.find((t) => t.fqName === 'edgar.company_financials')!;
  const finCols = fin.columns.map((c) => c.name).join(', ');
  const unionStages = stagePairs.map((p) => `    SELECT ticker, cik, entity_name, concept, xbrl_tag, tag_priority, fiscal_year, period_start, period_end, value_usd, form_type, filed_date, accession_number FROM edgar_stage.${p.stageName}`).join('\n    UNION ALL\n');
  const profileUnion = COMPANIES.map((co) => `    SELECT cik, '${co.ticker}' AS ticker, name AS entity_name, sic AS sic_code, \`sicDescription\` AS sic_description_edgar, \`stateOfIncorporation\` AS state_of_incorporation FROM sec_data.${co.slug}_submissions_raw`).join('\n    UNION ALL\n');
  files.push({
    name: '40_edgar_final_views.sql',
    content: BANNER('Step 40: edgar.company_financials and edgar.company_profile', `-- company_financials keeps ONE row per (ticker, concept, fiscal_year): latest period_end, then lowest tag_priority
-- (tag switch, recipe 01 caveat 1), then the latest filing (restatements). A window function is used instead of a self-join because
-- referencing a UNION ALL/explode view twice fails with MISSING_ATTRIBUTES (companion guide section 4).
-- If the window over the big UNION ALL is rejected, split it: one view per concept, then UNION ALL them.`) + `
CREATE SCHEMASTORE VIEW company_financials WITH CONTAINER edgar AS
SELECT ${finCols}
FROM (
    SELECT u.*, ROW_NUMBER() OVER (PARTITION BY ticker, concept, fiscal_year ORDER BY period_end DESC, tag_priority ASC, filed_date DESC) AS rn
    FROM (
${unionStages.split('\n').map((l) => '    ' + l).join('\n')}
    ) u
) ranked
WHERE rn = 1;

-- LEFT JOIN on purpose: recipe 11 uses INNER JOIN, which silently drops a company whose SIC code is missing from
-- the reference (IBM 3570). Here such a company stays, with NULL hierarchy columns.
CREATE SCHEMASTORE VIEW company_profile WITH CONTAINER edgar AS
SELECT
    s.cik AS cik,
    s.ticker AS ticker,
    s.entity_name AS entity_name,
    s.sic_code AS sic_code,
    s.sic_description_edgar AS sic_description_edgar,
    s.state_of_incorporation AS state_of_incorporation,
    r.description AS sic_description_reference,
    r.division AS division,
    r.division_desc AS division_desc,
    r.major_group AS major_group,
    r.major_group_desc AS major_group_desc,
    r.industry_group AS industry_group,
    r.industry_group_desc AS industry_group_desc
FROM (
${profileUnion}
) s
LEFT JOIN company_dns.sic_codes_v4_compat_table r
    ON s.sic_code = r.sic_code;
`,
  });

  // ---- 50: World Bank macro
  const wbStmts: string[] = [];
  const wbSelects: string[] = [];
  for (const ind of WB_INDICATORS) {
    const name = `wb_${wbShort(ind.id)}_usa`;
    raw.push({ db: 'WORLDBANK_REST', table: name, endpoint: wbUrl(ind.id) });
    wbStmts.push(`${restTable('WORLDBANK_REST', name, wbUrl(ind.id), '')}\n\nCACHE TABLE worldbank_rest.${name};`);
    wbSelects.push(`    SELECT countryiso3code AS country_code, indicator.id AS indicator_id, indicator.value AS indicator_name, CAST(\`date\` AS INT) AS year, CAST(\`value\` AS DOUBLE) AS value\n    FROM worldbank_rest.${name} WHERE indicator IS NOT NULL`);
  }
  files.push({
    name: '50_worldbank_macro.sql',
    content: BANNER(`Step 50: World Bank macro indicators (${WB_COUNTRY}, ${WB_DATE_RANGE})`, `-- RISK: the API returns a TOP-LEVEL JSON ARRAY [ {page,pages,...}, [ {indicator,country,date,value,...}, ... ] ].
-- Whether CREATE LIGHTNING REST TABLE accepts a bare top-level array is UNCONFIRMED (companion guide section 2
-- item 3). The view below ASSUMES each array element becomes a row with fields indicator, countryiso3code, date,
-- value (element 0, the paging metadata, has no 'indicator' so it is filtered out) and that the nested data array
-- is flattened. If CREATE/queries fail, use the fallback in data/README.md (upload data/csv/us_macro_indicators.csv
-- as a filestore table and create worldbank.us_macro_indicators over it).`) + `
${wbStmts.join('\n\n')}

CREATE SCHEMASTORE VIEW us_macro_indicators WITH CONTAINER worldbank AS
SELECT country_code, indicator_id, indicator_name, year, value
FROM (
${wbSelects.join('\n    UNION ALL\n')}
) m;
`,
  });

  // ---- 60: USL sic_edgar_usl
  const submissionsActivation = COMPANIES.map((co) => `    SELECT cik, '${co.ticker}' AS ticker, name AS entity_name, sic, \`sicDescription\` AS sic_description_edgar FROM sec_data.${co.slug}_submissions_raw`).join('\n    UNION ALL\n');
  files.push({
    name: '60_usl_sic_edgar.sql',
    content: BANNER('Step 60: Unified Semantic Layer sic_edgar_usl (company FK-> sic_code)', `-- Adapted from usl/sql/02_sic_edgar_usl_create.sql. Differences: 9 peers, a ticker column, SIC rows come from the
-- company_dns V4 raw table (explode(data)) instead of the deprecated V3 map-shaped one. The multi-table COMPILE USL
-- is ONE statement (the runner keeps the CREATE TABLEs attached). Activating from the V4 raw table is untested.
-- IBM-style gap: any peer whose SIC code is absent from the reference shows up as an invalid FK record in RUN DQ.`) + `
CREATE NAMESPACE IF NOT EXISTS lightning.metastore;
CREATE NAMESPACE IF NOT EXISTS lightning.metastore.usl_demo;

COMPILE USL IF NOT EXISTS sic_edgar_usl DEPLOY NAMESPACE lightning.metastore.usl_demo DDL
CREATE TABLE sic_code (
    sic_code varchar(4) NOT NULL PRIMARY KEY,
    description varchar(200),
    division varchar(1),
    division_desc varchar(200),
    major_group varchar(2),
    major_group_desc varchar(200),
    industry_group varchar(3),
    industry_group_desc varchar(200)
);

CREATE TABLE company (
    cik varchar(10) NOT NULL PRIMARY KEY,
    ticker varchar(10),
    entity_name varchar(200) NOT NULL,
    sic varchar(4) NOT NULL FOREIGN KEY REFERENCES sic_code(sic_code),
    sic_description_edgar varchar(200)
);

UPDATE USL lightning.metastore.usl_demo.sic_edgar_usl SET DESCRIPTION 'Causa semantic layer - nine retail and auto peers from SEC EDGAR linked to the SIC industry hierarchy so questions can ask whether companies share an industry.';
UPDATE USL lightning.metastore.usl_demo.sic_edgar_usl.company SET TABLE DESCRIPTION 'One row per peer company - CIK, ticker, name and SIC code as reported by EDGAR submissions.';
UPDATE USL lightning.metastore.usl_demo.sic_edgar_usl.sic_code SET TABLE DESCRIPTION 'SIC hierarchy reference from company_dns V4 under V3 column names.';

ACTIVATE USL TABLE lightning.metastore.usl_demo.sic_edgar_usl.sic_code AS
SELECT
    item.class_id AS sic_code,
    item.class_desc AS description,
    item.section_id AS division,
    item.section_desc AS division_desc,
    item.division_id AS major_group,
    item.division_desc AS major_group_desc,
    item.group_id AS industry_group,
    item.group_desc AS industry_group_desc
FROM company_dns.sic_codes_v4_raw
LATERAL VIEW explode(data) AS item;

ACTIVATE USL TABLE lightning.metastore.usl_demo.sic_edgar_usl.company AS
SELECT
    COALESCE(cik, '') AS cik,
    ticker,
    COALESCE(entity_name, '') AS entity_name,
    COALESCE(sic, '') AS sic,
    sic_description_edgar
FROM (
${submissionsActivation}
) AS companies;

RUN DQ TABLE lightning.metastore.usl_demo.sic_edgar_usl.company;
`,
  });

  // ---- 70: read-only verification
  files.push({
    name: '70_verify.sql',
    content: BANNER('Step 70: read-only verification (run after 10-60; compare with data.sec.gov / company_dns directly, companion guide section 6)') + `
SHOW LIGHTNING DATABASES;
SELECT count(*) AS n FROM company_dns.sic_codes_v4_table;
SELECT count(*) AS n FROM edgar.company_profile;
SELECT ticker, count(*) AS facts FROM edgar.company_financials GROUP BY ticker ORDER BY ticker;
SELECT ticker, fiscal_year, value_usd FROM edgar.company_financials WHERE concept = 'revenue' AND ticker IN ('WMT', 'TGT') ORDER BY fiscal_year, ticker;
SELECT indicator_id, count(*) AS n FROM worldbank.us_macro_indicators GROUP BY indicator_id;
SELECT count(*) AS n FROM lightning.metastore.usl_demo.sic_edgar_usl.company;
`,
  });

  return { files, rawTables: raw };
}
